_SENTIMENT_META = {
    "positive":   {"label": "Позитивный",  "emoji": "😊", "tone": "ok"},
    "neutral":    {"label": "Нейтральный", "emoji": "😐", "tone": "info"},
    "anxious":    {"label": "Тревожный",   "emoji": "😟", "tone": "warn"},
    "aggressive": {"label": "Напряжённый", "emoji": "😠", "tone": "danger"},
}


def _hits(text: str, markers) -> int:
    return sum(1 for m in markers if m in text)


def analyze_sentiment(text: str) -> dict:
    """Возвращает {key, label, emoji, tone} — эмоциональный окрас обращения."""
    t = (text or "").lower()
    if not t.strip():
        meta = _SENTIMENT_META["neutral"]
        return {"key": "neutral", **meta}

    aggr = _hits(t, _AGGRESSIVE)
    anx = _hits(t, _ANXIOUS)
    pos = _hits(t, _POSITIVE)

    # Восклицательные знаки и капс усиливают «напряжённость».
    bangs = t.count("!")
    if bangs >= 3:
        aggr += 1

    if aggr and aggr >= anx:
        key = "aggressive"
    elif anx:
        key = "anxious"
    elif pos:
        key = "positive"
    else:
        key = "neutral"
    return {"key": key, **_SENTIMENT_META[key]}


