def summarize(text: str, max_len: int = 90) -> str:
    """Однострочная «суть» обращения."""
    raw = (text or "").strip()
    if not raw:
        return ""

    low = raw.lower()
    for keys, label in _GIST_RULES:
        if any(k in low for k in keys):
            return label

    # Фолбэк: первое предложение, очищенное и подрезанное по границе слова.
    first = re.split(r"(?<=[.!?])\s+", raw)[0].strip()
    first = re.sub(r"\s+", " ", first)
    if len(first) <= max_len:
        return first
    cut = first[:max_len].rsplit(" ", 1)[0]
    return cut.rstrip(",.;:—- ") + "…"
