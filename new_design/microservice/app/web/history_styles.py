def coerce_kind(value: str) -> str:
    v = (value or "").strip().lower()
    return v if v in ALL_KINDS else "info"


def coerce_status(value: str) -> str:
    v = (value or "").strip().lower()
    if v in STATUSES:
        return v
    # Терпимо к синонимам, которые может вернуть модель.
    if v in ("done", "completed", "готово"):
        return "выполнено"
    if v in ("planned", "scheduled", "план"):
        return "запланировано"
    if v in ("progress", "in_progress", "ongoing"):
        return "в работе"
    return "выполнено"


def coerce_style(value: str, status: str = "") -> str:
    v = (value or "").strip().lower()
    if v in ALL_STYLES:
        return v
    return STATUS_DEFAULT_STYLE.get(status, "info")


def icon_for(kind: str) -> str:
    return ICON_BY_KIND.get(coerce_kind(kind), "info")
