"""Простой офлайн-классификатор тематики обращения по ключевым словам.

Используется для колонки «Тематика вопроса» в таск-трекере и для среза
«Тематики обращений» в аналитике. Не требует обращения к LLM — работает мгновенно
и предсказуемо. При желании можно заменить на классификацию через Dify.
"""
from __future__ import annotations

# Порядок важен: первая сработавшая категория и берётся.
TOPICS: list[tuple[str, tuple[str, ...]]] = [
    ("Выплаты и компенсации", ("выплат", "компенсац", "пособи", "деньг", "единовремен", "пенси")),
    ("Льготы и меры поддержки", ("льгот", "мер поддерж", "меры поддерж", "субсид", "налог")),
    ("Трудоустройство", ("работ", "трудоустр", "ваканс", "занятост", "професси")),
    ("Образование и переобучение", ("обуч", "переобуч", "образован", "курс", "переподготов", "квалификац")),
    ("Жильё", ("жиль", "квартир", "ипотек", "жилищн", "общежит", "переселен")),
    ("Медицина и реабилитация", ("медиц", "лечен", "реабилит", "санатор", "протез", "врач", "здоров", "инвалид")),
    ("Психологическая помощь", ("психолог", "стресс", "депресс")),
    ("Юридическая помощь", ("юрид", "юрист", "право", "суд", "документ", "оформ")),
    ("Статус ветерана", ("ветеран", "удостоверен", "статус", "вбд")),
    ("Розыск", ("розыск", "пропал", "без вести", "днк")),
    ("Запись на приём", ("запис", "приём", "прием", "встреч", "консультац")),
]

OTHER = "Прочее"


def classify_topic(text: str) -> str:
    t = (text or "").lower()
    for name, keys in TOPICS:
        if any(k in t for k in keys):
            return name
    return OTHER
